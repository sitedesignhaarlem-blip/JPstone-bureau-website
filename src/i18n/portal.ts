export const portalUI: Record<'en' | 'nl', PortalUI> = { en, nl };

/** Portal language: ?lang=, then the 'lang' cookie, then the browser's language; English if we have no texts. */
export function portalLang(url: URL, request: Request, cookie?: string): 'en' | 'nl' {
  const pick = (v?: string | null) => (v === 'nl' || v === 'en' ? v : null);
  return pick(url.searchParams.get('lang')) ?? pick(cookie)
    ?? (/^nl\b/i.test(request.headers.get('accept-language') ?? '') ? 'nl' : 'en');
}

export const fill = (s: string, vars: Record<string, string | number>) => s.replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ''));
