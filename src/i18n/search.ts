/** Anchor id for a question on the FAQ page, so search results can link straight to it. */
export function faqAnchor(question: string): string {
  const slug = question
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-|-$/g, '')
    .slice(0, 60);
  return `q-${slug}`;
}
